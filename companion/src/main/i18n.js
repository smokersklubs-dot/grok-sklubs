/** @param {string} locale @param {'auto'|'fr'|'en'} [pref] */
function pickLanguage(locale, pref = 'auto') {
  if (pref === 'fr' || pref === 'en') return pref;
  return /^fr\b/i.test(locale || '') ? 'fr' : 'en';
}

/** @param {'fr'|'en'} lang */
function strings(lang) {
  return lang === 'en' ? en : fr;
}

/** @param {Record<string,string>} dict @param {string} key @param {Record<string, string|number>} [vars] */
function t(dict, key, vars = {}) {
  const s = dict[key] || /** @type {Record<string,string>} */ (fr)[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

module.exports = { pickLanguage, strings, t, fr, en };
