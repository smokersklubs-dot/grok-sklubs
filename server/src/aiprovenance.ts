import sharp from "sharp";
import { hasAiLabel, labelAiImage } from "./aimedia.js";
import { hasAiVideoLabel, isIsoBmff, labelAiVideo, topBoxes } from "./aivideo.js";

/**
 * Audit Open Generative AI §2 "Étiquette IA" / §5 item 2 — media saved with media_save (a video an app such as
 * Higgsfield just made, a picture from another generator) now get the same "généré par IA" marker as video_generate and
 * image_generate (aivideo.ts, aimedia.ts), when we know they were generated:
 *  - the address is on a known generator's host (GENERATOR_HOSTS), or
 *  - the bot says so (media_save's `ai_generated`), or
 *  - the file already carries an AI marker (kept as is).
 *
 * Existing provenance is NEVER stripped. A file that already has provenance metadata is kept byte for byte:
 *  - C2PA (Content Credentials): a JUMBF box labelled "c2pa" (JPEG APP11, the `caBX` chunk of PNG, a `C2PA` WebP chunk)
 *    or the C2PA `uuid` box of an MP4 (C2PA Technical Specification 2.1, §A "Embedding manifests into assets",
 *    https://c2pa.org/specifications/specifications/2.1/specs/C2PA_Specification.html). Appending or re-encoding would
 *    break its hash binding;
 *  - an XMP packet (pictures: sharp's metadata().xmp; videos: the XMP `uuid` box): writing ours would replace or shadow it.
 * Re-encoding a picture to add XMP would also drop its EXIF, so a picture with any of these is left alone; the chat line
 * still says it was generated.
 */

/** Hosts whose media are made by an AI generator (suffix match). Read-only list: adding one only ever adds the label. */
export const GENERATOR_HOSTS = [
  "higgsfield.ai", "fal.media", "fal.run", "replicate.delivery", "replicate.com", "runwayml.com", "lumalabs.ai", "pika.art",
  "klingai.com", "hailuoai.com", "minimax.io", "minimaxi.com", "pixverse.ai", "vidu.com", "ideogram.ai", "leonardo.ai",
  "midjourney.com", "stability.ai", "krea.ai", "x.ai", "oaiusercontent.com", "openai.com", "fish.audio",
];

export function generatorHost(url: string): string | null {
  let host = "";
  try { host = new URL(url).hostname.toLowerCase(); } catch { return null; }
  return GENERATOR_HOSTS.find((h) => host === h || host.endsWith(`.${h}`)) ?? null;
}

/** The C2PA manifest box of an MP4 (C2PA spec: `uuid` box d8fec3d6-1b0e-483c-9297-5828877ec481). */
const C2PA_BMFF_UUID = Buffer.from("d8fec3d61b0e483c92975828877ec481", "hex");
const XMP_BMFF_UUID = Buffer.from("be7acfcb97a942e89c71999491e3afac", "hex");

/** Whether the bytes carry C2PA or XMP provenance (see above). */
export async function hasProvenance(bytes: Buffer, mime: string): Promise<boolean> {
  if (mime.startsWith("video/")) {
    if (!isIsoBmff(bytes)) return false;
    return topBoxes(bytes).some((b) => b.type === "uuid" && b.size >= 24 && (bytes.subarray(b.start + 8, b.start + 24).equals(C2PA_BMFF_UUID) || bytes.subarray(b.start + 8, b.start + 24).equals(XMP_BMFF_UUID)));
  }
  // JUMBF superbox ("jumb") with a C2PA description ("c2pa"): JPEG APP11, PNG caBX, WebP C2PA chunk all embed it.
  const head = bytes.subarray(0, Math.min(bytes.length, 4_000_000));
  if (head.includes("jumb") && head.includes("c2pa")) return true;
  if (mime === "image/png" && head.includes("caBX")) return true;
  try { const m = await sharp(bytes).metadata(); return !!m.xmp || !!m.exif; } catch { return false; }
}

export interface SavedLabel { bytes: Buffer; outcome: "labelled" | "already" | "kept" | "unlabelled" | "not-generated" }

/**
 * The saved file with the "generated by AI" marker when it is a generated file we may label; never loses the file and
 * never strips an existing marker or provenance.
 */
export async function labelSavedMedia(bytes: Buffer, mime: string, generated: boolean): Promise<SavedLabel> {
  const video = mime.startsWith("video/");
  if (video ? hasAiVideoLabel(bytes) : await hasAiLabel(bytes)) return { bytes, outcome: "already" };
  if (!generated) return { bytes, outcome: "not-generated" };
  if (await hasProvenance(bytes, mime)) return { bytes, outcome: "kept" };
  const out = video ? labelAiVideo(bytes, mime) : await labelAiImage(bytes, mime);
  return { bytes: out, outcome: out === bytes ? "unlabelled" : "labelled" };
}
