/**
 * Wan2GP runs that survive a restart (audit Open Generative AI §3.2, idea from its src/lib/pendingJobs.js — written for
 * the server here, not the browser's localStorage).
 *
 * A run is written down BEFORE it is submitted (status "submitting"), its Wan2GP job id as soon as Wan2GP answers
 * ("running"). The tool follows it during the turn; if the turn ends first (the run takes longer than the tool waits) or
 * the server restarts, a background poller picks it up by its job id — at start-up for a server address, and when the
 * owner's PC comes back online for a run through the Relais — and posts the finished file in the bot's chat. The user
 * stopping the turn cancels the run on the GPU. Nothing here costs money: Wan2GP runs on the owner's own GPU.
 */
q.run(`CREATE TABLE IF NOT EXISTS media_jobs (
  id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE, bot_id TEXT NOT NULL,
  provider TEXT NOT NULL, kind TEXT NOT NULL, job_id TEXT, status TEXT NOT NULL, filename TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '', created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL)`);
q.run("CREATE INDEX IF NOT EXISTS media_jobs_by_status ON media_jobs (status)");

export type MediaKind = "video" | "image";
export interface MediaJob { id: string; user_id: string; bot_id: string; provider: string; kind: MediaKind; job_id: string | null; status: string; filename: string; detail: string; created_at: number; updated_at: number }

export const mediaJobs = {
  start(f: { userId: string; botId: string; kind: MediaKind; filename: string }): string {
    const id = newId("mj");
    q.run("INSERT INTO media_jobs (id, user_id, bot_id, provider, kind, status, filename, created_at, updated_at) VALUES (?, ?, ?, 'wan2gp', ?, 'submitting', ?, ?, ?)", id, f.userId, f.botId, f.kind, f.filename, now(), now());
    return id;
  },
  running(id: string, jobId: string) { q.run("UPDATE media_jobs SET job_id = ?, status = 'running', updated_at = ? WHERE id = ?", jobId, now(), id); },
  end(id: string, status: "done" | "failed" | "cancelled", detail = "") { q.run("UPDATE media_jobs SET status = ?, detail = ?, updated_at = ? WHERE id = ?", status, detail.slice(0, 500), now(), id); },
  get: (id: string) => q.get<MediaJob>("SELECT * FROM media_jobs WHERE id = ?", id) ?? null,
  /** Runs left open (by a restart, or handed to the background poller). */
  open: () => q.all<MediaJob>("SELECT * FROM media_jobs WHERE status = 'running' AND job_id IS NOT NULL ORDER BY created_at"),
  forUser: (userId: string) => q.all<MediaJob>("SELECT * FROM media_jobs WHERE user_id = ? ORDER BY created_at DESC LIMIT 20", userId),
};

const EXT: Record<string, string> = { mp4: "video/mp4", webm: "video/webm", mov: "video/quicktime", mkv: "video/x-matroska", png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", webp: "image/webp" };

/** Downloads the finished item, labels it "generated by AI" and keeps it in the bot's library (images/ or videos/). */
export async function keepResult(client: Wan2gpClient, job: Pick<MediaJob, "bot_id" | "kind" | "filename">, item: GalleryItem) {
  const { filename, bytes } = await client.download(item.media_id);
  const ext = (/\.([a-z0-9]+)$/i.exec(filename || item.filename || "")?.[1] ?? (job.kind === "video" ? "mp4" : "png")).toLowerCase();
  const mime = EXT[ext] ?? (job.kind === "video" ? "video/mp4" : "image/png");
  // L30: the same "generated by AI" marker as every other generated file (aivideo.ts, aimedia.ts).
  const labelled = mime.startsWith("video/") ? labelAiVideo(bytes, mime) : await labelAiImage(bytes, mime);
  return storeBytes(job.bot_id, job.kind === "video" ? "videos" : "images", `${job.filename}.${ext}`, labelled);
}

/** Runs being followed right now, in this process (never twice). */
const following = new Set<string>();
export const isFollowing = (id: string) => following.has(id);
export function follow(id: string, on: boolean) { if (on) following.add(id); else following.delete(id); }

/** Background poller: follows an open run to its end and posts the file in the bot's chat. */
export async function resumeJob(job: MediaJob, why: "restart" | "long", o: { target?: Wan2gpTarget | null; intervalMs?: number } = {}): Promise<void> {
  if (following.has(job.id) || !job.job_id) return;
  const bot = bots.byId(job.bot_id);
  const target = o.target ?? wan2gpTarget(job.user_id);
  if (!bot || !target) { mediaJobs.end(job.id, "failed", "Wan2GP is no longer set up"); return; }
  following.add(job.id);
  try {
    const client = wan2gpClient(job.user_id, target, { id: bot.id, name: bot.name });
    const item = await client.poll(job.job_id, { intervalMs: o.intervalMs ?? (Number(process.env.WAN2GP_POLL_MS) || undefined), untilMs: Date.now() + 6 * 3600_000 });
    if (item === "waiting") { mediaJobs.end(job.id, "failed", "still not finished after 6 hours"); return; }
    const att = await keepResult(client, job, item);
    mediaJobs.end(job.id, "done", att.path);
    const text = tr(users.localeOf(job.user_id), why === "restart" ? "Your Wan2GP creation is ready (picked up again after a server restart). Free, made on your GPU." : "Your Wan2GP creation is ready. Free, made on your GPU.");
    rows.append(bot, { kind: "message", role: "assistant", text, attachments: [att] });
    bots.bumpUnread(bot.id);
  } catch (err) {
    const msg = String((err as Error)?.message ?? err);
    // The Relais went offline mid-way: the run stays open and is picked up when the PC comes back.
    if (/offline|not connected|the Relais answered (offline|disconnected)/i.test(msg)) return;
    mediaJobs.end(job.id, /cancelled/i.test(msg) ? "cancelled" : "failed", msg);
    rows.append(bot, { kind: "event", event: "relay", text: `Wan2GP : ${msg.slice(0, 200)}`, tone: "warn" });
  } finally { following.delete(job.id); }
}

/** Start-up: open runs on a server address are followed now; runs on a PC when its Relais connects. */
export function startMediaJobs() {
  for (const job of mediaJobs.open()) {
    const t = wan2gpTarget(job.user_id);
    if (!t) { mediaJobs.end(job.id, "failed", "Wan2GP is no longer set up"); continue; }
    if (t.mode === "url" || liveDevice(job.user_id, t.deviceId)) void resumeJob(job, "restart", { target: t });
  }
}
whenOnline((userId, deviceId, capabilities) => {
  if (!capabilities.includes("gpu.http")) return;
  for (const job of mediaJobs.open()) {
    if (job.user_id !== userId) continue;
    const t = wan2gpTarget(userId);
    if (t?.mode === "relay" && t.deviceId === deviceId) void resumeJob(job, "restart", { target: t });
  }
});

/** "40 %" for the live line. */
export const pct = (p: Wan2gpProgress) => Math.round(p.progress * 100);
