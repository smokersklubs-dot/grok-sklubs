import { aiXmp, AI_SOURCE_TYPE } from "./aimedia.js";

/**
 * L30 (security report limit: pictures were labelled, videos were not) — "généré par IA" in the metadata of the videos
 * the bots create.
 *
 * What is written: the same XMP packet as the pictures (aimedia.ts), carrying the IPTC "Digital Source Type"
 * (`Iptc4xmpExt:DigitalSourceType`, IPTC Photo Metadata Standard; vocabulary https://cv.iptc.org/newscodes/digitalsourcetype/):
 *  - `trainedAlgorithmicMedia` for a clip made by a video model (video_generate, video.ts);
 *  - `compositeWithTrainedAlgorithmicMedia` for a Studio montage the owner marked « Généré par IA » (it mixes the owner's
 *    own media with generated parts).
 * These are the same URIs the C2PA specification uses for `digitalSourceType` in its actions assertion (C2PA Technical
 * Specification, "Actions" assertion, https://c2pa.org/specifications/specifications/2.1/specs/C2PA_Specification.html).
 * We do NOT write a signed C2PA manifest (that needs a signing certificate): only the IPTC marker, which is what
 * players, search engines and social networks read today.
 *
 * Where: MP4 / QuickTime only, as a top-level `uuid` box with the XMP UUID BE7ACFCB-97A9-42E8-9C71-999491E3AFAC
 * (Adobe XMP Specification Part 3 "Storage in files", MPEG-4 section: XMP in a top-level UUID box; the same box
 * ExifTool reads as "XMP" in MP4/MOV, https://exiftool.org/TagNames/QuickTime.html).
 * The box is APPENDED at the end of the file: nothing before it moves, so the sample offsets (stco/co64) stay valid
 * and no re-encoding is needed. ffmpeg's mov muxer cannot write XMP (it only writes iTunes-style udta tags), hence this
 * small writer, which works even where ffmpeg is not installed. WebM and other formats are returned unchanged: the chat
 * still says the video was generated.
 */
export const COMPOSITE_SOURCE_TYPE = "http://cv.iptc.org/newscodes/digitalsourcetype/compositeWithTrainedAlgorithmicMedia";
const XMP_UUID = Buffer.from("be7acfcb97a942e89c71999491e3afac", "hex");

/** An ISO-BMFF file (MP4, MOV, M4V): its first box is `ftyp`. */
export const isIsoBmff = (bytes: Buffer) => bytes.length >= 12 && bytes.toString("ascii", 4, 8) === "ftyp";

/** The top-level boxes of an ISO-BMFF file: type, start and size. Stops at the first malformed size. */
export function topBoxes(bytes: Buffer): { type: string; start: number; size: number }[] {
  const out: { type: string; start: number; size: number }[] = [];
  let at = 0;
  while (at + 8 <= bytes.length) {
    let size = bytes.readUInt32BE(at);
    const type = bytes.toString("latin1", at + 4, at + 8);
    if (size === 1) {
      if (at + 16 > bytes.length) break;
      const big = bytes.readBigUInt64BE(at + 8);
      if (big > BigInt(bytes.length - at)) break;
      size = Number(big);
    } else if (size === 0) size = bytes.length - at; // "to the end of the file"
    if (size < 8 || at + size > bytes.length) break;
    out.push({ type, start: at, size });
    at += size;
  }
  return out;
}

/** The XMP `uuid` box to append (box header + UUID + packet). */
export function xmpBox(sourceType = AI_SOURCE_TYPE): Buffer {
  const xmp = Buffer.from(aiXmp("Sklubot", sourceType), "utf8");
  const head = Buffer.alloc(8);
  head.writeUInt32BE(8 + 16 + xmp.length, 0);
  head.write("uuid", 4, "latin1");
  return Buffer.concat([head, XMP_UUID, xmp]);
}

/** The XMP packet of a labelled MP4 (from its top-level XMP uuid box), or null. */
export function videoXmp(bytes: Buffer): string | null {
  if (!isIsoBmff(bytes)) return null;
  for (const b of topBoxes(bytes)) {
    if (b.type === "uuid" && b.size > 24 && bytes.subarray(b.start + 8, b.start + 24).equals(XMP_UUID)) return bytes.toString("utf8", b.start + 24, b.start + b.size);
  }
  return null;
}

/** Whether a video carries the "generated by AI" marker (either kind). */
export function hasAiVideoLabel(bytes: Buffer): boolean {
  const x = videoXmp(bytes);
  return !!x && x.includes("digitalsourcetype/") && x.includes("DigitalSourceType");
}

/**
 * The video with the marker, or the same bytes when it cannot be written (not an MP4, a file whose boxes do not add
 * up to its size, already labelled). Never loses the video.
 */
export function labelAiVideo(bytes: Buffer, mime = "video/mp4", sourceType = AI_SOURCE_TYPE): Buffer {
  if (!/^video\/(mp4|quicktime|x-m4v)$/i.test(mime) || !isIsoBmff(bytes) || hasAiVideoLabel(bytes)) return bytes;
  const boxes = topBoxes(bytes);
  const last = boxes.at(-1);
  // Appending is only safe when the boxes cover the whole file (a trailing size-0 box would swallow ours otherwise).
  if (!last || last.start + last.size !== bytes.length || bytes.readUInt32BE(last.start) === 0) return bytes;
  return Buffer.concat([bytes, xmpBox(sourceType)]);
}

/**
 * The same marker appended to a large MP4 on disk (a Studio export can reach 1 GB: never read whole). Walks the
 * top-level box headers only; appends when they add up to the file size. Returns the new size (unchanged when not written).
 */
export async function labelAiVideoFile(file: import("node:fs/promises").FileHandle, size: number, sourceType = AI_SOURCE_TYPE): Promise<number> {
  const head = Buffer.alloc(24);
  let at = 0, lastSize = -1;
  while (at + 8 <= size) {
    const { bytesRead } = await file.read(head, 0, 24, at);
    if (bytesRead < 8) return size;
    let box = head.readUInt32BE(0);
    const type = head.toString("latin1", 4, 8);
    if (at === 0 && type !== "ftyp") return size;
    if (box === 1) { if (bytesRead < 16) return size; box = Number(head.readBigUInt64BE(8)); } else if (box === 0) return size; // size 0 would swallow our box
    if (box < 8 || at + box > size) return size;
    if (type === "uuid" && bytesRead >= 24 && head.subarray(8, 24).equals(XMP_UUID)) return size; // already labelled
    lastSize = box;
    at += box;
  }
  if (at !== size || lastSize < 0) return size;
  const add = xmpBox(sourceType);
  await file.write(add, 0, add.length, size);
  return size + add.length;
}
