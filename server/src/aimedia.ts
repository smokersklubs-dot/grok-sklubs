import sharp from "sharp";

/**
 * L30 — "généré par IA" on the pictures the bots create (image_generate, images.ts). Each picture gets an XMP packet with
 * the IPTC "Digital Source Type" of synthetic media: `Iptc4xmpExt:DigitalSourceType` =
 * http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia (IPTC Photo Metadata Standard, "Digital Source
 * Type" property, and the IPTC NewsCodes vocabulary "digitalsourcetype", https://cv.iptc.org/newscodes/digitalsourcetype/),
 * the field that photo apps, search engines and social networks read to show "made with AI". Written with sharp's
 * withXmp() (node_modules/sharp/lib/index.d.ts), PNG kept lossless, JPEG and WebP re-encoded at quality 95.
 *
 * A picture whose format sharp cannot write, or that fails to decode, is returned unchanged (never lost): the chat still
 * says it was generated. Videos are not tagged here (that needs a muxer on the bot's computer): said in the docs.
 */
export const AI_SOURCE_TYPE = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia";

export function aiXmp(tool = "Sklubot"): string {
  const esc = (s: string) => s.replace(/[<>&"]/g, (c) => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;" })[c]!);
  return `<?xpacket begin="\uFEFF" id="W5M0MpCehiHzreSzNTczkc9d"?>
<x:xmpmeta xmlns:x="adobe:ns:meta/">
 <rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">
  <rdf:Description rdf:about="" xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/" xmlns:xmp="http://ns.adobe.com/xap/1.0/" xmlns:dc="http://purl.org/dc/elements/1.1/"
   Iptc4xmpExt:DigitalSourceType="${AI_SOURCE_TYPE}" xmp:CreatorTool="${esc(tool)}">
   <dc:description><rdf:Alt><rdf:li xml:lang="x-default">Generated by AI / Généré par IA</rdf:li></rdf:Alt></dc:description>
  </rdf:Description>
 </rdf:RDF>
</x:xmpmeta>
<?xpacket end="w"?>`;
}

/** The picture with the "generated by AI" label in its metadata (same format), or unchanged when it cannot be written. */
export async function labelAiImage(bytes: Buffer, mime: string): Promise<Buffer> {
  try {
    const img = sharp(bytes, { failOn: "error" }).withXmp(aiXmp());
    if (mime === "image/png") return await img.png().toBuffer();
    if (mime === "image/jpeg") return await img.jpeg({ quality: 95 }).toBuffer();
    if (mime === "image/webp") return await img.webp({ quality: 95 }).toBuffer();
    return bytes;
  } catch { return bytes; }
}

/** Whether a picture carries the label (tests, and the library's "AI" badge if one is added later). */
export async function hasAiLabel(bytes: Buffer): Promise<boolean> {
  try { const m = await sharp(bytes).metadata(); return !!m.xmp && m.xmp.toString("utf8").includes(AI_SOURCE_TYPE); } catch { return false; }
}
